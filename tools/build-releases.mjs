/** Refresh the optional OFFLINE snapshot from PUBLIC releases of the website repo.
 * Online browsing uses the API directly and does not depend on this command.
 * Node 22+. No dependencies, auth tokens, JAR downloads or Markdown execution.
 */
import fs from 'node:fs/promises';
import path from 'node:path';
import vm from 'node:vm';
import { pathToFileURL } from 'node:url';
import { randomUUID } from 'node:crypto';
import github from '../assets/js/core/github-releases.js';

export async function buildSnapshot(root, options = {}) {
  const siteRoot=path.resolve(root);
  const configPath=path.join(siteRoot,'assets/js/data/site-config.js');
  const context=vm.createContext({window:{}});
  vm.runInContext(await fs.readFile(configPath,'utf8'),context,{filename:configPath,timeout:1000});
  const config=context.window.COREX_SITE?.releases;
  github.repository(config); // fail before modifying any files on invalid configuration
  // Intentionally unauthenticated: a typo pointing at a private repo must fail closed.
  const records=await github.fetchAll(config,options.fetch || globalThis.fetch);
  const payload=github.makeSnapshot(records,config,(options.now ? options.now() : new Date()).toISOString());
  const normalized=github.normalizeReleases(payload.releases,config);
  const out=path.join(siteRoot,'assets/js/generated/releases.js');
  let previous=null;
  try {
    const source=await fs.readFile(out,'utf8');
    const match=source.match(/window\.COREX_RELEASES\s*=\s*([\s\S]+);\s*$/);
    if(match)previous=JSON.parse(match[1]);
  } catch(e) {if(e.code && e.code!=='ENOENT')throw e;}
  if(previous?.generatedAt && previous.schemaVersion===2 && previous.provider==='github' && previous.repository===payload.repository && JSON.stringify(previous.releases)===JSON.stringify(payload.releases)) {
    return {changed:false,count:normalized.releases.length,warnings:normalized.warnings};
  }
  const serialized=JSON.stringify(payload,null,2).replace(/</g,'\\u003c').replace(/\u2028/g,'\\u2028').replace(/\u2029/g,'\\u2029');
  const js='/* Optional PUBLIC GitHub release snapshot. Generated by tools/build-releases.mjs; no binaries or credentials. */\nwindow.COREX_RELEASES = '+serialized+';\n';
  await fs.mkdir(path.dirname(out),{recursive:true});
  const temporary=out+'.tmp-'+randomUUID();
  try {await fs.writeFile(temporary,js,'utf8');await fs.rename(temporary,out);}
  finally {await fs.rm(temporary,{force:true});}
  return {changed:true,count:normalized.releases.length,warnings:normalized.warnings};
}

if(process.argv[1] && pathToFileURL(path.resolve(process.argv[1])).href===import.meta.url) {
  try {
    const result=await buildSnapshot(process.argv[2]||'.');
    for(const warning of result.warnings)console.warn(warning);
    console.log(`${result.changed?'Updated':'Unchanged'} public GitHub snapshot: ${result.count} downloadable release(s).`);
  } catch(error) {
    console.error(`GitHub snapshot failed; previous file retained. ${error.message}`);
    process.exitCode=1;
  }
}
